const testing = std.testing;

/// The default device inside a fresh autorelease pool, or error.SkipZigTest without Metal.
const TestGpu = struct {
    pool: objc.Object,
    device: Device,

    fn begin() !TestGpu {
        const raw_pool = objc.msgSend(?objc.Object, objc.class("NSAutoreleasePool"), "alloc", .{});
        const pool = objc.msgSend(?objc.Object, raw_pool, "init", .{}) orelse return error.PoolInitFailed;
        errdefer objc.msgSend(void, pool, "drain", .{});
        const device = Device.createSystemDefault() orelse return error.SkipZigTest;
        return .{ .pool = pool, .device = device };
    }

    fn end(self: TestGpu) void {
        self.device.release();
        objc.msgSend(void, self.pool, "drain", .{});
    }
};

test "binding slots follow the spec's table, and no stage reuses a slot" {
    try testing.expectEqual(0, binding.VERTICES);
    try testing.expectEqual(1, binding.SKY_VIEW_PROJ);
    try testing.expectEqual(1, binding.SKY_UNIFORMS);
    try testing.expectEqual(1, binding.SHADOW_MVP);
    try testing.expectEqual(1, binding.MVP);
    try testing.expectEqual(2, binding.MODEL);
    try testing.expectEqual(3, binding.LIGHT_VIEW_PROJ);
    try testing.expectEqual(4, binding.HIT_TIMERS);
    try testing.expectEqual(0, binding.LIGHT_UNIFORMS);
    try testing.expectEqual(0, binding.ALBEDO_TEXTURE);
    try testing.expectEqual(1, binding.SHADOW_MAP_TEXTURE);
    try testing.expectEqual(1, binding.CROSSHAIR_UNIFORMS);

    // vertex_main's five buffers are distinct; the sky's fragment uniforms never sit in LightUniforms' slot.
    const vertex_main_slots = [_]u64{
        binding.VERTICES, binding.MVP, binding.MODEL, binding.LIGHT_VIEW_PROJ, binding.HIT_TIMERS,
    };
    for (vertex_main_slots, 0..) |a, i| {
        for (vertex_main_slots[i + 1 ..]) |b| try testing.expect(a != b);
    }
    try testing.expect(binding.SKY_UNIFORMS != binding.LIGHT_UNIFORMS);
    try testing.expect(binding.ALBEDO_TEXTURE != binding.SHADOW_MAP_TEXTURE);
    try testing.expect(binding.VERTICES != binding.CROSSHAIR_UNIFORMS);
}

test "both shader sources start with the generated prelude" {
    inline for (.{ scene_shader_source, crosshair_shader_source }) |source| {
        try testing.expect(std.mem.startsWith(u8, source, prelude));
        try testing.expect(std.mem.find(u8, source, "#include <metal_stdlib>") != null);
        inline for (comptime std.meta.declarations(binding)) |name| {
            const define = std.fmt.comptimePrint("#define BIND_{s} {d}\n", .{ name, @field(binding, name) });
            try testing.expect(std.mem.find(u8, source, define) != null);
        }
        try testing.expect(std.mem.find(u8, source, "#define SHADOW_MAP_SIZE 2048\n") != null);
        try testing.expect(std.mem.find(u8, source, "#define SIZEOF_LIGHT_UNIFORMS 64\n") != null);
        try testing.expect(std.mem.find(u8, source, "#define OFFSETOF_LIGHT_COLOR 32\n") != null);
    }
    try testing.expect(std.mem.find(u8, scene_shader_source, "fragment float4 fragment_main(") != null);
    try testing.expect(std.mem.find(u8, crosshair_shader_source, "vertex CrosshairOut crosshair_vertex(") != null);
    // Right after the prelude, each source renumbers its lines so diagnostics point into the .msl file.
    try testing.expect(std.mem.startsWith(u8, scene_shader_source[prelude.len..], "#line 1 \"scene.msl\"\n// Scene shaders"));
    try testing.expect(std.mem.startsWith(u8, crosshair_shader_source[prelude.len..], "#line 1 \"crosshair.msl\"\n// Crosshair"));
}

test "Pipelines.init compiles both shaders and builds every pipeline and depth state" {
    const gpu = try TestGpu.begin();
    defer gpu.end();

    var pipelines = try Pipelines.init(gpu.device);
    defer pipelines.deinit();

    // Every state is a distinct live object (a shared handle would mean a copy-paste slip in init).
    const handles = [_]objc.Object{
        pipelines.scene_instanced.handle, pipelines.scene_single.handle, pipelines.shadow_instanced.handle,
        pipelines.shadow_single.handle,   pipelines.sky.handle,          pipelines.crosshair.handle,
        pipelines.depth_default.handle,   pipelines.depth_sky.handle,    pipelines.depth_overlay.handle,
    };
    for (handles, 0..) |a, i| {
        for (handles[i + 1 ..]) |b| try testing.expect(a != b);
    }
    // The labels reach Metal (they name pipelines in GPU captures and in creation-failure logs).
    const label = objc.msgSend(?objc.Object, pipelines.shadow_single.handle, "label", .{}) orelse
        return error.TestUnexpectedResult;
    try testing.expectEqualStrings("shadow single", objc.fromNSString(label));
}
