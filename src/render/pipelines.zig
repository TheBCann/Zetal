//! Render pipelines and depth states for the shadow, sky, scene and crosshair draws, and the shader sources they compile.

const std = @import("std");
const objc = @import("../objc.zig");
const metal = @import("metal.zig");
const geometry = @import("geometry.zig");
const uniforms = @import("uniforms.zig");
const SHADOW_MAP_SIZE = @import("renderer.zig").SHADOW_MAP_SIZE;

const Device = metal.Device;
const Library = metal.Library;
const Function = metal.Function;
const RenderPipelineState = metal.RenderPipelineState;
const DepthStencilState = metal.DepthStencilState;

// ============================================================
// Attachment formats and binding slots
// ============================================================

/// Colour format of every main-pass pipeline; must equal the CAMetalLayer's pixelFormat (80).
pub const COLOR_FORMAT: metal.PixelFormat = .bgra8_unorm;
/// Depth format of every pipeline, the shadow map and the main-pass depth target.
pub const DEPTH_FORMAT: metal.PixelFormat = .depth32_float;

/// The [[buffer(n)]] / [[texture(n)]] slots of the scene and crosshair shaders. renderer.zig binds
/// with these and each reaches the MSL as `#define BIND_<NAME> n`, so the two sides cannot disagree.
pub const binding = struct {
    /// Vertex buffer of every vertex function: Vertex[] (scene, shadow) or float4[] (sky, crosshair).
    pub const VERTICES: u64 = 0;
    /// skybox_vertex: the camera view-projection (float4x4).
    pub const SKY_VIEW_PROJ: u64 = 1;
    /// skybox_fragment: SkyUniforms, in its own slot so it never displaces LightUniforms.
    pub const SKY_UNIFORMS: u64 = 1;
    /// shadow_vertex: one light MVP per instance; shadow_vertex_single: a single light MVP.
    pub const SHADOW_MVP: u64 = 1;
    /// vertex_main: one MVP per instance; vertex_single: a single MVP.
    pub const MVP: u64 = 1;
    /// vertex_main: one model matrix per instance; vertex_single: a single model matrix.
    pub const MODEL: u64 = 2;
    /// vertex_main / vertex_single: the light view-projection (float4x4).
    pub const LIGHT_VIEW_PROJ: u64 = 3;
    /// vertex_main: one hit-flash timer per instance (float).
    pub const HIT_TIMERS: u64 = 4;
    /// fragment_main: LightUniforms.
    pub const LIGHT_UNIFORMS: u64 = 0;
    /// fragment_main texture: the albedo (texture2d<float>).
    pub const ALBEDO_TEXTURE: u64 = 0;
    /// fragment_main texture: the shadow map (depth2d<float>).
    pub const SHADOW_MAP_TEXTURE: u64 = 1;
    /// crosshair_vertex: CrosshairUniforms.
    pub const CROSSHAIR_UNIFORMS: u64 = 1;
};

// ============================================================
// Shader sources
// ============================================================

// The `#line` after the shared prelude makes Metal's diagnostics name the .msl file and its own line
// numbers (the prelude is shared by both, so it cannot carry the directive itself).

/// MSL for the sky, shadow and lit scene draws: the generated prelude followed by shaders/scene.msl.
pub const scene_shader_source: [:0]const u8 = prelude ++ "#line 1 \"scene.msl\"\n" ++ @embedFile("shaders/scene.msl");
/// MSL for the crosshair overlay: the generated prelude followed by shaders/crosshair.msl.
pub const crosshair_shader_source: [:0]const u8 = prelude ++ "#line 1 \"crosshair.msl\"\n" ++ @embedFile("shaders/crosshair.msl");

/// The #defines both shaders start with: one BIND_* per `binding` slot, the shadow-map size, and the
/// Zig struct sizes and offsets the MSL static_asserts its own structs against. Integers only: an
/// MSL float define would need an explicit ".0f" (`{d}` prints 2.0 as "2").
const prelude: [:0]const u8 = blk: {
    var text: [:0]const u8 = "// ---- generated by render/pipelines.zig ----\n";
    for (std.meta.declarations(binding)) |name| {
        text = text ++ std.fmt.comptimePrint("#define BIND_{s} {d}\n", .{ name, @field(binding, name) });
    }
    break :blk text ++ std.fmt.comptimePrint(
        \\#define SHADOW_MAP_SIZE {d}
        \\#define SIZEOF_VERTEX {d}
        \\#define SIZEOF_LIGHT_UNIFORMS {d}
        \\#define OFFSETOF_LIGHT_VIEW_POS {d}
        \\#define OFFSETOF_LIGHT_COLOR {d}
        \\#define OFFSETOF_LIGHT_AMBIENT {d}
        \\#define OFFSETOF_LIGHT_SHININESS {d}
        \\#define SIZEOF_SKY_UNIFORMS {d}
        \\#define SIZEOF_CROSSHAIR_UNIFORMS {d}
        \\#define OFFSETOF_CROSSHAIR_HIT_MARKER {d}
        \\// ---- end of generated prelude ----
        \\
    , .{
        SHADOW_MAP_SIZE,
        @sizeOf(geometry.Vertex),
        @sizeOf(uniforms.LightUniforms),
        @offsetOf(uniforms.LightUniforms, "view_pos"),
        @offsetOf(uniforms.LightUniforms, "light_color"),
        @offsetOf(uniforms.LightUniforms, "ambient_strength"),
        @offsetOf(uniforms.LightUniforms, "shininess"),
        @sizeOf(uniforms.SkyUniforms),
        @sizeOf(uniforms.CrosshairUniforms),
        @offsetOf(uniforms.CrosshairUniforms, "hit_marker"),
    });
};

// ============================================================
// Pipelines
// ============================================================

/// Every render pipeline and depth-stencil state the renderer uses (+1 each; `deinit` releases them).
pub const Pipelines = struct {
    /// vertex_main + fragment_main: the instanced cubes.
    scene_instanced: RenderPipelineState,
    /// vertex_single + fragment_main: the ground and the gun.
    scene_single: RenderPipelineState,
    /// shadow_vertex, depth only: the instanced cubes into the shadow map.
    shadow_instanced: RenderPipelineState,
    /// shadow_vertex_single, depth only: the ground into the shadow map.
    shadow_single: RenderPipelineState,
    /// skybox_vertex + skybox_fragment.
    sky: RenderPipelineState,
    /// crosshair_vertex + crosshair_fragment.
    crosshair: RenderPipelineState,
    /// Less, writes on: the shadow casters, the world and the gun.
    depth_default: DepthStencilState,
    /// LessEqual, writes off: the sky sits at depth 1.0, passes against the 1.0 clear and hides nothing.
    depth_sky: DepthStencilState,
    /// Always, writes off: the crosshair overlay.
    depth_overlay: DepthStencilState,

    /// Compiles both shaders and builds every state. Call inside an autorelease pool (labels and
    /// NSErrors are autoreleased); on failure Metal's reason has been logged.
    pub fn init(device: Device) !Pipelines {
        const scene_library = try device.newLibrary(scene_shader_source);
        defer scene_library.release();
        const crosshair_library = try device.newLibrary(crosshair_shader_source);
        defer crosshair_library.release();

        const scene_instanced = try buildPipeline(device, scene_library, "scene instanced", "vertex_main", "fragment_main");
        errdefer scene_instanced.release();
        const scene_single = try buildPipeline(device, scene_library, "scene single", "vertex_single", "fragment_main");
        errdefer scene_single.release();
        const shadow_instanced = try buildPipeline(device, scene_library, "shadow instanced", "shadow_vertex", null);
        errdefer shadow_instanced.release();
        const shadow_single = try buildPipeline(device, scene_library, "shadow single", "shadow_vertex_single", null);
        errdefer shadow_single.release();
        const sky = try buildPipeline(device, scene_library, "sky", "skybox_vertex", "skybox_fragment");
        errdefer sky.release();
        const crosshair = try buildPipeline(device, crosshair_library, "crosshair", "crosshair_vertex", "crosshair_fragment");
        errdefer crosshair.release();

        const depth_default = try device.newDepthStencilState(.less, true);
        errdefer depth_default.release();
        const depth_sky = try device.newDepthStencilState(.less_equal, false);
        errdefer depth_sky.release();
        const depth_overlay = try device.newDepthStencilState(.always, false);

        return .{
            .scene_instanced = scene_instanced,
            .scene_single = scene_single,
            .shadow_instanced = shadow_instanced,
            .shadow_single = shadow_single,
            .sky = sky,
            .crosshair = crosshair,
            .depth_default = depth_default,
            .depth_sky = depth_sky,
            .depth_overlay = depth_overlay,
        };
    }

    /// Releases every state.
    pub fn deinit(self: *Pipelines) void {
        self.scene_instanced.release();
        self.scene_single.release();
        self.shadow_instanced.release();
        self.shadow_single.release();
        self.sky.release();
        self.crosshair.release();
        self.depth_default.release();
        self.depth_sky.release();
        self.depth_overlay.release();
        self.* = undefined;
    }
};

/// Returns the pipeline (+1) running `vertex_name` and `fragment_name` from `library`. Pixel formats
/// are always set (the descriptor defaults to Invalid): colour 0 = COLOR_FORMAT and depth =
/// DEPTH_FORMAT, or, with a null fragment function, a depth-only pipeline for the shadow pass.
fn buildPipeline(
    device: Device,
    library: Library,
    label: [:0]const u8,
    vertex_name: [:0]const u8,
    fragment_name: ?[:0]const u8,
) !RenderPipelineState {
    const desc = try metal.RenderPipelineDescriptor.create();
    defer desc.release();
    desc.setLabel(label);

    const vertex_fn = try library.newFunction(vertex_name);
    defer vertex_fn.release();
    desc.setVertexFunction(vertex_fn);

    const fragment_fn: ?Function = if (fragment_name) |name| try library.newFunction(name) else null;
    defer if (fragment_fn) |f| f.release();
    desc.setFragmentFunction(fragment_fn);
    if (fragment_fn != null) desc.setColorPixelFormat(0, COLOR_FORMAT);
    desc.setDepthPixelFormat(DEPTH_FORMAT);

    return device.newRenderPipelineState(desc);
}

